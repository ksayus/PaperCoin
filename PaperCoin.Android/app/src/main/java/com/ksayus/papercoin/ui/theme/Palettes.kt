import androidx.compose.ui.graphics.Color

/** 一套主题的 32 个颜色。字段与 Themes 下 6 本调色板字典的 key 一一对应，由脚本生成。 */
data class AppColors(
    val glassBackdrop: Color,
    val glassScrim: Color,
    val titleTop: Color,
    val sideBar: Color,
    val mainContentArea: Color,
    val cardBackground: Color,
    val cardBorder: Color,
    val cardActionBackground: Color,
    val sideBarBtn: Color,
    val sideBarBtnOver: Color,
    val sideBarBtnActive: Color,
    val sideBarBtnPressed: Color,
    val addNewBillBtn: Color,
    val addNewBillBtnOver: Color,
    val addNewBillBtnPressed: Color,
    val textTitle: Color,
    val textSecondary: Color,
    val positive: Color,
    val negative: Color,
    val shadow: Color,
    val windowShadow: Color,
    val categoryColors: List<Color>,
    val categoryOther: Color,
) {
    fun categoryColor(key: String): Color {
        val index = key.removePrefix("CategoryColor").toIntOrNull()
        return if (index != null && index in 1..categoryColors.size) categoryColors[index - 1] else categoryOther
    }
}

